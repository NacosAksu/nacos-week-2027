// 1. Renders every template with its PreviewProps to emails/out/<name>.html and .txt (to look at).
// 2. Renders the templates with %%TOKEN%% placeholders into backend/email-templates.gs,
//    which registration.gs fills in and sends. Re-run after any template change, then paste
//    that file into Apps Script.
// (`email export` in react-email 6 renders without props, which crashes templates that need data.)
import { mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { createElement } from 'react';
import { createJiti } from 'jiti';
import { render } from 'react-email';

const dir = new URL('.', import.meta.url);
const out = new URL('out/', dir);
mkdirSync(out, { recursive: true });
const jiti = createJiti(import.meta.url, { jsx: { runtime: 'automatic' } });
const load = (name) => jiti.import(new URL(`${name}.tsx`, dir).href, { default: true });

// Gmail clips messages over ~102 KB
const size = (html) => {
  const kb = Buffer.byteLength(html) / 1024;
  return `${kb.toFixed(1)} KB${kb > 100 ? '  <-- over Gmail clip limit' : ''}`;
};

console.log('Previews (emails/out):');
for (const file of readdirSync(dir).filter((f) => f.endsWith('.tsx'))) {
  const name = file.replace(/\.tsx$/, '');
  const Email = await load(name);
  const el = createElement(Email, Email.PreviewProps);
  const html = await render(el);
  writeFileSync(new URL(`${name}.html`, out), html);
  writeFileSync(new URL(`${name}.txt`, out), await render(el, { plainText: true }));
  console.log(`  ${name}: ${size(html)}`);
}

// ---------- Apps Script templates ----------
const { reminder, awardNight, partnership } = await jiti.import(new URL('_data/campaigns.ts', dir).href);
const T = (key) => `%%${key}%%`;
// firstName() splits on the space, so greetings get %%FIRST%% and full names get both tokens.
const NAME = '%%FIRST%% %%REST%%';

const variants = {
  registration: ['registration-confirmed', { name: NAME, passId: T('ID'), department: T('DEPARTMENT'), interests: [T('INTEREST')] }],
  volunteer: ['volunteer-application', { name: NAME, volunteerId: T('ID'), team: T('TEAM'), availability: T('AVAILABILITY'), groupUrl: T('GROUP_URL') }],
  volunteer_no_group: ['volunteer-application', { name: NAME, volunteerId: T('ID'), team: T('TEAM'), availability: T('AVAILABILITY'), groupUrl: '' }],
  announcement: ['programme-announcement', { recipientName: T('FIRST') }],
  partnership: ['partnership-invitation', { contactName: T('CONTACT'), company: T('COMPANY'), ...partnership }],
};
if (reminder) {
  variants.reminder = ['event-reminder', { name: NAME, passId: T('ID'), daysToGo: T('DAYS'), ...reminder }];
  variants.reminder_one_day = ['event-reminder', { name: NAME, passId: T('ID'), daysToGo: 1, ...reminder }];
}
if (awardNight) {
  const guest = { guestName: T('GUEST'), seats: T('SEATS'), ...awardNight };
  variants.award = ['award-night-invitation', { ...guest, nomination: T('NOMINATION') }];
  variants.award_no_nomination = ['award-night-invitation', guest];
}

const templates = {};
console.log('\nApps Script templates (backend/email-templates.gs):');
for (const [key, [name, props]] of Object.entries(variants)) {
  const el = createElement(await load(name), props);
  const html = await render(el);
  templates[key] = { html, text: await render(el, { plainText: true }) };
  console.log(`  ${key}: ${size(html)}`);
}
const skipped = [!reminder && 'reminder', !awardNight && 'award'].filter(Boolean);
if (skipped.length) console.log(`  not built yet (fill emails/_data/campaigns.ts): ${skipped.join(', ')}`);

writeFileSync(
  new URL('../backend/email-templates.gs', dir),
  `// GENERATED by \`npm run email:export\` from the React Email templates in /emails. Do not edit by hand:\n` +
    `// change the .tsx files, re-run the export, then paste this whole file into the Apps Script project\n` +
    `// as a second file named email-templates.gs. registration.gs fills the %%TOKENS%% and sends.\n` +
    `var EMAIL_TEMPLATES = ${JSON.stringify(templates)};\n`,
);
